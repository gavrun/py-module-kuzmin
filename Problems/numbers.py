binary_num = 0b1010  # 10 in decimal
print(binary_num)

# Convert decimal to binary:
print(bin(10))

octal_num = 0o12  # 10 in decimal
print(octal_num)

# Convert decimal to octal:
print(oct(10))

hex_num = 0x1f  # 31 in decimal
print(hex_num)

# Convert decimal to hex:
print(hex(31)) 

# Underscores
million = 1_000_000
binary = 0b_1010_1010
hex_val = 0xFF_FF_FF
print(million)
print(binary)
print(hex_val)

# Scientific 
large = 1.23e+5  # 123000.0
small = 1.23e-5  # 0.0000123
print(large)
print(small)

